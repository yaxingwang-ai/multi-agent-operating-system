"""Multi-Agent Workflow (V1.2).

User Request -> Research Agent -> validate -> Investment Analyst -> validate
-> Final Report. The workflow stops at the first failed stage, so a later
agent never runs on missing or invalid input and no partial report is built.
"""

from collections.abc import Callable

from maos.agents import investment_analyst, research_agent
from maos.contracts import (
    InvestmentAnalysis,
    ResearchReport,
    WorkflowRequest,
    WorkflowResult,
    parse_sections,
)

STAGE_RESEARCH = "research"
STAGE_ANALYST = "analyst"

ResearchFn = Callable[[WorkflowRequest], str]
AnalystFn = Callable[[WorkflowRequest, ResearchReport], str]

REPORT_TITLE = "MAOS Investment Research Report"

DISCLAIMER = (
    "**Not investment advice.** This report was generated by AI agents from "
    "model knowledge only. No live search or market data was used, its facts "
    "and sources have not been verified and may be out of date. The analyst "
    "is instructed not to give buy, sell, or hold recommendations; treat any "
    "such statement as an error. Do not use this report to make investment "
    "decisions."
)


class WorkflowStageError(Exception):
    """Raised when a stage fails; the original error is ``__cause__``.

    The message names only the stage, because the cause's message can echo
    part of the API key.
    """

    def __init__(self, stage: str):
        self.stage = stage
        super().__init__(f"{stage} stage failed")


def _run_stage(stage: str, expected: tuple[str, ...], call: Callable[[], str]):
    """Run one agent call and validate its output; return (sections, markdown)."""
    try:
        output = call()
        markdown = "" if output is None else str(output)
        return parse_sections(markdown, expected), markdown
    except Exception as exc:
        raise WorkflowStageError(stage) from exc


def render_report(
    request: WorkflowRequest, research: ResearchReport, analysis: InvestmentAnalysis
) -> str:
    """Build the final Markdown report. Deterministic: no dates or randomness."""
    request_lines = research_agent.format_research_input(
        request.request, request.subject, request.topic, request.period
    ).splitlines()

    lines = [f"# {REPORT_TITLE}", "", f"> {DISCLAIMER}", "", "## Request", ""]
    lines += [f"- {line}" for line in request_lines]
    for part, sections in (
        ("Part 1: Research", research.sections),
        ("Part 2: Investment Analysis", analysis.sections),
    ):
        lines += ["", f"## {part}"]
        for name, body in sections.items():
            lines += ["", f"### {name}", "", body]
    lines += ["", "## Disclaimer", "", DISCLAIMER]
    return "\n".join(lines) + "\n"


def run_workflow(
    request: WorkflowRequest,
    *,
    model: str | None = None,
    research_fn: ResearchFn | None = None,
    analyst_fn: AnalystFn | None = None,
) -> WorkflowResult:
    """Run the full workflow once.

    ``research_fn`` and ``analyst_fn`` default to the real agents, which use
    ``model``. Tests pass mock agents instead.

    Raises:
        WorkflowStageError: a stage failed or returned invalid output.
    """
    if research_fn is None:
        def research_fn(req):
            return research_agent.run_research(
                req.request, subject=req.subject, topic=req.topic,
                period=req.period, model=model,
            )
    if analyst_fn is None:
        def analyst_fn(req, research):
            return investment_analyst.run_investment_analysis(req, research, model=model)

    sections, markdown = _run_stage(
        STAGE_RESEARCH, research_agent.OUTPUT_SECTIONS, lambda: research_fn(request)
    )
    research = ResearchReport(sections=sections, markdown=markdown)

    sections, markdown = _run_stage(
        STAGE_ANALYST, investment_analyst.OUTPUT_SECTIONS,
        lambda: analyst_fn(request, research),
    )
    analysis = InvestmentAnalysis(sections=sections, markdown=markdown)

    return WorkflowResult(
        request=request,
        research=research,
        analysis=analysis,
        report_markdown=render_report(request, research, analysis),
    )
